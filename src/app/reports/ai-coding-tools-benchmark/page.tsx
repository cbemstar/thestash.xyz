function buildBenchmarkBriefMarkdown({
  title,
  updatedAt,
  rows,
  marketMetrics,
  officialReports,
  sources,
}: {
  title: string;
  updatedAt: string;
  rows: ReturnType<typeof getAiCodingBenchmarkRows>;
  marketMetrics: ReturnType<typeof getIndustryMetricsForToolSlugs>;
  officialReports: ReturnType<typeof getOfficialBenchmarkReports>;
  sources: Array<{ label: string; url: string }>;
}): string {
  const lines: string[] = [];
  lines.push(`# ${title}`);
  lines.push("");
  lines.push(`Updated: ${new Date(updatedAt).toLocaleDateString("en-US")}`);
  lines.push(`Tools benchmarked: ${rows.length}`);
  lines.push("");
  lines.push("## Top benchmark rows");
  rows.slice(0, 8).forEach((row, index) => {
    lines.push(
      `${index + 1}. ${row.tool} - score ${row.score} (setup ${row.setupSpeedScore}, collab ${row.collaborationScore}, extensibility ${row.extensibilityScore}, pricing ${row.pricingPredictabilityScore}, lock-in ${row.lockInRiskScore})`
    );
  });
  lines.push("");
  lines.push("## Official report highlights");
  officialReports.forEach((report) => {
    lines.push(`- ${report.organization} - ${report.title} (${report.publishedLabel})`);
    report.metrics.forEach((metric) => {
      lines.push(`  - ${metric.value}: ${metric.detail}`);
    });
    lines.push(`  - Source: ${report.reportUrl}`);
  });
  lines.push("");
  lines.push("## Latest market signals");
  marketMetrics.forEach((metric) => {
    lines.push(`- ${metric.metric} (${metric.sourceLabel})`);
  });
  lines.push("");
  lines.push("## Sources");
  sources.forEach((source) => {
    lines.push(`- ${source.label}: ${source.url}`);
  });
  lines.push("");
  lines.push("Generated by The Stash benchmark page.");
  return lines.join("\n");
}

function DatasetJsonLd() {
  const summary = getAiCodingBenchmarkSummary();
  const canonical = `${BASE_URL}${REPORT_PATH}`;
  const jsonLd = {
    "@context": "https://schema.org",
    "@type": "Dataset",
    name: summary.title,
    description: summary.description,
    url: canonical,
    dateModified: summary.updatedAt,
    creator: {
      "@type": "Organization",
      name: "The Stash",
    },
    distribution: [
      {
        "@type": "DataDownload",
        encodingFormat: "application/json",
        contentUrl: `${BASE_URL}/api/seo/benchmark/ai-coding-tools`,
      },
      {
        "@type": "DataDownload",
        encodingFormat: "text/csv",
        contentUrl: `${BASE_URL}/api/seo/benchmark/ai-coding-tools?format=csv`,
      },
    ],
  };
  return (
    <script
      type="application/ld+json"
      dangerouslySetInnerHTML={{ __html: JSON.stringify(jsonLd) }}
    />
  );
}

